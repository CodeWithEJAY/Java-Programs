public class Lab3_Arithmetic {
    public static void main(String[] args) {

        double num1 = 15.0;
        double num2 = 4.0;

        double sum = num1 + num2;
        double difference = num1 - num2;
        double product = num1 * num2;
        double quotient = num1 / num2;
        double remainder = num1 % num2;

        double average = (num1 + num2) / 2;
        double square1 = num1 * num1;
        double square2 = num2 * num2;

        System.out.println("===== Arithmetic Results =====");
        System.out.println("Number 1       : " + num1);
        System.out.println("Number 2       : " + num2);
        System.out.println("Sum            : " + sum);
        System.out.println("Difference     : " + difference);
        System.out.println("Product        : " + product);
        System.out.println("Quotient       : " + quotient);
        System.out.println("Remainder      : " + remainder);
        System.out.println("Average        : " + average);
        System.out.println("Square of 15   : " + square1);
        System.out.println("Square of 4    : " + square2);

        int intNum1 = 15;
        int intNum2 = 4;

        int intQuotient = intNum1 / intNum2;

        System.out.println("\n===== Integer Division =====");
        System.out.println("Number 1       : " + intNum1);
        System.out.println("Number 2       : " + intNum2);
        System.out.println("Quotient       : " + intQuotient);
    }
}
