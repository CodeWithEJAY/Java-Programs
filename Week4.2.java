public class Lab_2Constants {
    public static void main(String[] args) {

        final double PI = 3.14159;
        final int MAX_SCORE = 100;
        final int PASSING_GRADE = 75;

        int studentScore = 93;
        boolean didPass = studentScore >= PASSING_GRADE;

        System.out.println("===== Constants and Variables =====");
        System.out.println("Value of PI       : " + PI);
        System.out.println("Maximum Score     : " + MAX_SCORE);
        System.out.println("Passing Grade     : " + PASSING_GRADE);
        System.out.println("Student Score     : " + studentScore);
        System.out.println("Did the student pass?: " + didPass);
    }
}
